#!/usr/bin/env node

"use strict";

/**
 * Render a compact AGENTS.md from Claude-owned project guidance.
 *
 * Claude Code loads CLAUDE.md plus target-scoped `.claude/rules/*.md`. Codex and OpenCode load
 * AGENTS.md but do not implement Claude's per-target `paths` activation. Copying every source body
 * is therefore both semantically misleading and larger than Codex's documented 32 KiB default
 * project-instructions budget. This renderer projects selected handbook sections and emits an
 * explicit dispatch entry for every scoped rule.
 *
 * `--from-index` exists for pre-commit. Reading the working tree there would copy unstaged source
 * edits into AGENTS.md and stage them accidentally; the index is the exact content being committed.
 */

const assert = require("node:assert/strict");
const { execFileSync } = require("node:child_process");
const {
  existsSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} = require("node:fs");
const path = require("node:path");

const REPO_ROOT = path.resolve(__dirname, "..");
const HANDBOOK = "CLAUDE.md";
const RULES_DIRECTORY = ".claude/rules";
const TARGET = "AGENTS.md";
const MAX_PROJECT_GUIDANCE_BYTES = 32 * 1024;

// Selection is intentionally explicit: content remains authored only in CLAUDE.md, while changes
// to the downstream always-loaded surface stay reviewable in this projection contract.
const PROJECTED_HANDBOOK_SECTIONS = Object.freeze([
  "Core Principles",
  "Node.js Support Boundaries",
  "Validation Gates (one contract, impact-aware subsets)",
  "Documentation Map",
  "Command Reference (run inside `server/`)",
  "Domain Ownership Matrix (ENFORCED)",
  "Key Constraints",
]);

const HEADER = `<!-- GENERATED by scripts/sync-project-guidance.js.
     Source of truth: CLAUDE.md and .claude/rules/*.md.
     This is a compact semantic projection, not a concatenation.
     Do not edit this downstream compatibility file. -->`;

function normalizeMarkdown(content) {
  return content.replace(/\r\n/gu, "\n").trimEnd();
}

function sortSources(sources) {
  return [...sources].sort((left, right) => left.localeCompare(right, "en"));
}

function workingTreeSources(root = REPO_ROOT) {
  const rulesRoot = path.join(root, RULES_DIRECTORY);
  const rules = existsSync(rulesRoot)
    ? readdirSync(rulesRoot, { withFileTypes: true })
        .filter((entry) => entry.isFile() && entry.name.endsWith(".md"))
        .map((entry) => `${RULES_DIRECTORY}/${entry.name}`)
    : [];
  return [HANDBOOK, ...sortSources(rules)];
}

function indexSources(root = REPO_ROOT) {
  const output = execFileSync(
    "git",
    ["ls-files", "-z", "--", HANDBOOK, `${RULES_DIRECTORY}/*.md`],
    { cwd: root, encoding: "utf8" },
  );
  const tracked = output.split("\0").filter(Boolean);
  if (!tracked.includes(HANDBOOK)) {
    throw new Error(`${HANDBOOK} is absent from the Git index`);
  }
  return [
    HANDBOOK,
    ...sortSources(tracked.filter((source) => source !== HANDBOOK)),
  ];
}

function readWorkingTreeSource(source, root = REPO_ROOT) {
  return readFileSync(path.join(root, source), "utf8");
}

function readIndexSource(source, root = REPO_ROOT) {
  const object = source === HANDBOOK ? ":CLAUDE.md" : `:${source}`;
  return execFileSync("git", ["show", object], {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 16 * 1024 * 1024,
  });
}

function handbookSections(content) {
  const normalized = normalizeMarkdown(content);
  const matches = [...normalized.matchAll(/^## (.+)$/gmu)];
  const sections = new Map();

  for (let index = 0; index < matches.length; index += 1) {
    const match = matches[index];
    const title = match[1].trim();
    if (sections.has(title)) {
      throw new Error(
        `${HANDBOOK} contains duplicate section ${JSON.stringify(title)}`,
      );
    }
    const end = matches[index + 1]?.index ?? normalized.length;
    sections.set(title, normalized.slice(match.index, end).trimEnd());
  }
  return sections;
}

function projectHandbook(content, selected = PROJECTED_HANDBOOK_SECTIONS) {
  const sections = handbookSections(content);
  return selected.map((title) => {
    const section = sections.get(title);
    if (!section) {
      throw new Error(
        `${HANDBOOK} is missing projected section ${JSON.stringify(title)}`,
      );
    }
    return section;
  });
}

function unquoteYamlScalar(value) {
  const trimmed = value.trim();
  if (
    (trimmed.startsWith('"') && trimmed.endsWith('"')) ||
    (trimmed.startsWith("'") && trimmed.endsWith("'"))
  ) {
    return trimmed.slice(1, -1);
  }
  return trimmed;
}

function parseRule(source, content) {
  const normalized = normalizeMarkdown(content);
  const frontmatter = /^---\n([\s\S]*?)\n---\n([\s\S]+)$/u.exec(normalized);
  if (!frontmatter) {
    throw new Error(`${source} must start with YAML frontmatter`);
  }
  if (/^globs\s*:/mu.test(frontmatter[1])) {
    throw new Error(
      `${source} uses unsupported \`globs:\`; Claude Code requires \`paths:\``,
    );
  }

  const lines = frontmatter[1].split("\n");
  const paths = [];
  let readingPaths = false;
  for (const line of lines) {
    if (/^paths\s*:\s*$/u.test(line)) {
      readingPaths = true;
      continue;
    }
    if (readingPaths) {
      const item = /^\s+-\s+(.+?)\s*$/u.exec(line);
      if (item) {
        paths.push(unquoteYamlScalar(item[1]));
        continue;
      }
      if (/^\S/u.test(line)) readingPaths = false;
    }
  }
  if (paths.length === 0 || paths.some((pattern) => pattern.length === 0)) {
    throw new Error(
      `${source} must declare at least one non-empty \`paths:\` pattern`,
    );
  }

  const body = frontmatter[2].trim();
  const title = /^# (.+)$/mu.exec(body)?.[1]?.trim();
  if (!title) {
    throw new Error(`${source} must contain one level-one title`);
  }
  return { source, title, paths };
}

function renderRuleDispatch(rule) {
  const patterns = rule.paths.map((pattern) => `\`${pattern}\``).join(", ");
  return `- **${rule.title}** (${patterns}) -> before editing a matching path, read [\`${rule.source}\`](${rule.source}) and treat it as mandatory project guidance.`;
}

function enforceByteBudget(rendered) {
  const bytes = Buffer.byteLength(rendered, "utf8");
  if (bytes > MAX_PROJECT_GUIDANCE_BYTES) {
    throw new Error(
      `${TARGET} projection is ${bytes} bytes; limit is ${MAX_PROJECT_GUIDANCE_BYTES}. ` +
        "Move detail to canonical docs or remove a projected handbook section.",
    );
  }
  return bytes;
}

function renderGuidance(sources, readSource) {
  if (sources[0] !== HANDBOOK) {
    throw new Error(`${HANDBOOK} must be the first projection source`);
  }
  const handbook = projectHandbook(readSource(HANDBOOK));
  const rules = sources
    .slice(1)
    .map((source) => parseRule(source, readSource(source)));
  const dispatch = rules.map(renderRuleDispatch).join("\n");
  const rendered = `${HEADER}

# Agent Rules · Claude Prompts MCP

## Canonical ownership and loading

- Edit \`CLAUDE.md\` and \`.claude/rules/*.md\`; do not edit this generated file.
- This compact file is the default Codex/OpenCode context. It preserves the project-wide decisions
  that change most tasks while staying within Codex's documented default 32 KiB project guidance
  budget.
- Claude Code applies rule \`paths:\` natively. Codex and OpenCode do not, so use the dispatch table
  below: when a task touches a matching path, read that canonical rule before editing.
- For project details not projected here, consult \`CLAUDE.md\` and its documentation pointers.

${handbook.join("\n\n")}

## Conditional project guidance

${dispatch || "No scoped project rules are defined."}
`;
  enforceByteBudget(rendered);
  return rendered;
}

function firstDifference(expected, actual) {
  const expectedLines = expected.split("\n");
  const actualLines = actual.split("\n");
  const count = Math.max(expectedLines.length, actualLines.length);
  for (let index = 0; index < count; index += 1) {
    if (expectedLines[index] !== actualLines[index]) {
      return `line ${index + 1}: expected ${JSON.stringify(expectedLines[index] ?? "<end>")} but found ${JSON.stringify(actualLines[index] ?? "<end>")}`;
    }
  }
  return "trailing bytes differ";
}

function expectedGuidance({ fromIndex = false, root = REPO_ROOT } = {}) {
  const sources = fromIndex ? indexSources(root) : workingTreeSources(root);
  const readSource = fromIndex
    ? (source) => readIndexSource(source, root)
    : (source) => readWorkingTreeSource(source, root);
  const bytes = renderGuidance(sources, readSource);
  return { bytes, byteCount: Buffer.byteLength(bytes, "utf8"), sources };
}

function check(options = {}) {
  const expected = expectedGuidance(options);
  const target = path.join(options.root ?? REPO_ROOT, TARGET);
  if (!existsSync(target)) {
    return { ...expected, drift: `${TARGET} is missing` };
  }
  const actual = readFileSync(target, "utf8");
  return {
    ...expected,
    drift:
      actual === expected.bytes
        ? null
        : firstDifference(expected.bytes, actual),
  };
}

function write(options = {}) {
  const rendered = expectedGuidance(options);
  writeFileSync(
    path.join(options.root ?? REPO_ROOT, TARGET),
    rendered.bytes,
    "utf8",
  );
  return rendered;
}

function selfTest() {
  const handbook = PROJECTED_HANDBOOK_SECTIONS.map(
    (title, index) => `## ${title}\r\n\r\nSection ${index}.\r\n`,
  ).join("\r\n");
  const sourceContent = new Map([
    [HANDBOOK, `# Handbook\r\n\r\n${handbook}`],
    [
      ".claude/rules/z-last.md",
      '---\npaths:\n  - "**/*.z"\n---\n\n# Z Rule\n\nSECRET RULE BODY\n',
    ],
    [
      ".claude/rules/a-first.md",
      "---\npaths:\n  - '**/*.a'\n---\n\n# A Rule\n",
    ],
  ]);
  const sources = [
    HANDBOOK,
    ...sortSources([...sourceContent.keys()].slice(1)),
  ];
  const rendered = renderGuidance(sources, (source) =>
    sourceContent.get(source),
  );

  assert.ok(rendered.startsWith(HEADER));
  assert.ok(rendered.indexOf("A Rule") < rendered.indexOf("Z Rule"));
  assert.ok(rendered.includes("## Core Principles\n\nSection 0."));
  assert.ok(rendered.includes("`**/*.z`"));
  assert.ok(!rendered.includes("SECRET RULE BODY"));
  assert.ok(!rendered.includes("\r"));
  assert.ok(Buffer.byteLength(rendered, "utf8") < MAX_PROJECT_GUIDANCE_BYTES);
  assert.match(firstDifference("a\nb\n", "a\nc\n"), /^line 2:/u);
  assert.throws(
    () => parseRule("bad.md", "---\nglobs:\n  - '**/*.ts'\n---\n# Bad"),
    /requires `paths:`/u,
  );
  assert.throws(
    () => projectHandbook("## Core Principles\nOnly one."),
    /missing projected section/u,
  );
  assert.throws(
    () => enforceByteBudget("x".repeat(MAX_PROJECT_GUIDANCE_BYTES + 1)),
    /limit is 32768/u,
  );

  process.stdout.write(
    "sync-project-guidance --self-test: 11/11 checks passed\n",
  );
}

function main() {
  const args = new Set(process.argv.slice(2));
  const known = new Set(["--write", "--check", "--from-index", "--self-test"]);
  const unknown = [...args].filter((arg) => !known.has(arg));
  if (unknown.length > 0) {
    throw new Error(`Unknown option(s): ${unknown.join(", ")}`);
  }
  if (args.has("--self-test")) {
    selfTest();
    return;
  }
  if (args.has("--write") === args.has("--check")) {
    throw new Error("Choose exactly one of --write or --check");
  }

  const options = { fromIndex: args.has("--from-index") };
  if (args.has("--write")) {
    const result = write(options);
    process.stdout.write(
      `sync-project-guidance: wrote ${TARGET} (${result.byteCount}/${MAX_PROJECT_GUIDANCE_BYTES} bytes) from ${result.sources.length} canonical source(s)\n`,
    );
    return;
  }

  const result = check(options);
  if (result.drift !== null) {
    process.stderr.write(
      `sync-project-guidance: ${TARGET} drifted from canonical Claude guidance — ${result.drift}\n` +
        "Run the `guidance:sync` script and commit the regenerated projection.\n",
    );
    process.exitCode = 1;
    return;
  }
  process.stdout.write(
    `sync-project-guidance: ${TARGET} matches ${result.sources.length} canonical source(s) (${result.byteCount}/${MAX_PROJECT_GUIDANCE_BYTES} bytes)\n`,
  );
}

if (require.main === module) {
  try {
    main();
  } catch (error) {
    process.stderr.write(`sync-project-guidance: ${error.message}\n`);
    process.exitCode = 1;
  }
}

module.exports = {
  check,
  enforceByteBudget,
  expectedGuidance,
  firstDifference,
  handbookSections,
  indexSources,
  normalizeMarkdown,
  parseRule,
  projectHandbook,
  renderGuidance,
  renderRuleDispatch,
  sortSources,
  workingTreeSources,
  write,
};
