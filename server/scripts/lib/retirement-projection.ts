// @lifecycle canonical - Renders the runtime projection of the retirement ledger.
/**
 * The runtime projection: `src/shared/utils/_generated/retirement-notices.ts`, the only form of
 * the ledger the product imports. It holds the three fields a refusal prints, so the bundles
 * carry neither the gate's fields (`kind`, `forgetAfter`, `docPattern`) nor the shape check.
 * `generate-retirements-doc.ts` writes it; `validate:retirements` (check 5) fails when the file on
 * disk is not what this renders.
 *
 * Each entry is its own exported constant, named by `projectionMember(id)`, and a refusal site
 * imports the module as a namespace and reads one member by name. A bundler then keeps only the
 * entries a bundle's code reads: `cpm` carries the config-file, layout and schema refusals, not
 * the server's transport or command-operator ones. An id-keyed map would carry every entry
 * into every bundle.
 *
 * The text is emitted as Prettier would format it, so the format gate accepts the bytes.
 */

import type { RetirementEntry } from './retirement-ledger.js';

/** Server-relative path of the generated projection. */
export const RETIREMENT_PROJECTION = 'src/shared/utils/_generated/retirement-notices.ts';

/** Prettier's `printWidth` for `server/**` (`.prettierrc.json`). */
const PRINT_WIDTH = 100;

/**
 * A string literal quoted the way Prettier quotes it under `singleQuote`: single quotes unless
 * the text holds more single quotes than double quotes.
 */
function quoteString(text: string): string {
  const singles = text.split("'").length - 1;
  const doubles = text.split('"').length - 1;
  const quote = singles > doubles ? '"' : "'";
  const escaped = text.replaceAll('\\', '\\\\').replaceAll(quote, `\\${quote}`);
  return `${quote}${escaped}${quote}`;
}

/** One `key: 'value',` property at `indent`, broken after the colon when it does not fit. */
function property(indent: string, key: string, value: string): string {
  const inline = `${indent}${key}: ${quoteString(value)},`;
  if (inline.length <= PRINT_WIDTH) return inline;
  return `${indent}${key}:\n${indent}  ${quoteString(value)},`;
}

const HEADER = `// Auto-generated by scripts/generate-retirements-doc.ts from tooling/contracts/registries/retirements.json.
// Do not edit manually — run \`npm run generate:retirements-doc\`. \`npm run validate:retirements\`
// fails when this file and the ledger disagree.
//
// The three fields a refusal prints, one constant per ledger entry refused in TypeScript. A
// refusal site imports this module as a namespace and reads one member by name, so each bundle
// keeps only what it reads. The ledger's other fields, its entries refused outside TypeScript and
// its shape check stay with the scripts (scripts/lib/retirement-ledger.ts).

import type { RetirementNotice } from '../retirement-notice.js';
`;

/**
 * Whether an entry has a projection member. An entry whose refusal lives outside TypeScript
 * (`refusalSites`) has none: nothing in the product reads it, and the bundles stay as they are.
 */
export function isProjected(entry: Pick<RetirementEntry, 'refusalSites'>): boolean {
  return entry.refusalSites === undefined;
}

/** The exported name of an entry's constant: its kebab-case id in camelCase. */
export function projectionMember(id: string): string {
  return id.replace(/-([a-z0-9])/g, (_match, next: string) => next.toUpperCase());
}

function renderEntry(entry: RetirementEntry): string {
  return [
    `/** ${entry.id} */`,
    `export const ${projectionMember(entry.id)}: RetirementNotice = {`,
    property('  ', 'retired', entry.retired),
    property('  ', 'replacement', entry.replacement),
    property('  ', 'refusedIn', entry.refusedIn),
    '};',
  ].join('\n');
}

/**
 * The projection module for the projected entries, in ledger order; pure. Two ids that share a
 * member name (`a-1b` and `a1b`) would make one constant shadow the other, so they are refused here.
 */
export function renderRetirementProjection(entries: readonly RetirementEntry[]): string {
  const projected = entries.filter(isProjected);
  const owners = new Map<string, string>();
  for (const { id } of projected) {
    const member = projectionMember(id);
    const earlier = owners.get(member);
    if (earlier !== undefined) {
      throw new Error(`retirements.json: '${earlier}' and '${id}' both project to ${member}`);
    }
    owners.set(member, id);
  }
  return [HEADER, projected.map(renderEntry).join('\n\n'), ''].join('\n');
}
