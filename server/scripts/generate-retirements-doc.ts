// @lifecycle canonical - Renders docs/reference/upgrading.md from the retirement ledger.
/**
 * Upgrade page generator.
 *
 * Reads `tooling/contracts/registries/retirements.json` through the same loader the refusal
 * sites use and writes `docs/reference/upgrading.md`: the one page where a user reads a name the
 * product no longer accepts. The ledger is the only place those names are written; the page is
 * derived, never edited by hand. `validate:retirements` (check 5) fails when the page on disk is
 * not what this renders.
 *
 * The page is emitted as Prettier would format it (a padded table, no trailing spaces), so
 * `validate:format` accepts the generated bytes and the page needs no `.prettierignore` line.
 *
 * Run: `npm run generate:retirements-doc`
 */

import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { listRetirements, type RetirementEntry } from './lib/retirement-ledger.js';
import { renderRetirementProjection, RETIREMENT_PROJECTION } from './lib/retirement-projection.js';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');

/** Repository-relative path of the generated page. */
export const UPGRADING_PAGE = 'docs/reference/upgrading.md';
export const GENERATE_COMMAND = 'npm --prefix server run generate:retirements-doc';

const HEADER_COMMENT = `<!-- Generated from server/tooling/contracts/registries/retirements.json by \`${GENERATE_COMMAND}\`. Edit the ledger, not this page. -->`;

const OPENING =
  'A spelling listed here is refused, and the refusal message names what to use instead. Find the spelling you wrote in the first column and use the form in the second.';

const CLOSING =
  'A spelling is in one of two states: accepted, or refused. A refusal is removed after the date in the last column, and from then on the old spelling is unknown input, treated like any other name the product does not recognise.';

/** Kinds whose retired spelling is a literal a user types, shown as code; the rest are phrases. */
const LITERAL_KINDS: ReadonlySet<RetirementEntry['kind']> = new Set([
  'environment-variable',
  'config-key',
  'config-file',
  'transport',
]);

const HEADER = ['What you wrote', 'What to use now', 'Refused since', 'Message removed after'];

function versionParts(version: string): number[] {
  return version.split('.').map(Number);
}

/** Newest refusing release first, then by the retired spelling. */
export function compareForPage(a: RetirementEntry, b: RetirementEntry): number {
  const left = versionParts(a.refusedIn);
  const right = versionParts(b.refusedIn);
  for (let index = 0; index < left.length; index += 1) {
    const difference = (right[index] ?? 0) - (left[index] ?? 0);
    if (difference !== 0) return difference;
  }
  return a.retired.localeCompare(b.retired);
}

/** A spelling a user types as one token: an identifier with no space and no code span of its own. */
const BARE_SPELLING = /^[^\s`]+$/;

/** A path or name holding a `<name>` placeholder, taken whole: `<workspace>/resources/<type>/`. */
const PLACEHOLDER_TOKEN = /[\w./-]*<[a-z][a-z-]*>[\w./<>-]*/g;

/**
 * A table cell: `|` escaped, and a token holding a `<name>` placeholder turned into one code span
 * so it is not HTML. Text already inside a code span is left as written.
 */
function cell(text: string): string {
  return text
    .split(/(`[^`]*`)/)
    .map((segment) =>
      segment.startsWith('`')
        ? segment
        : segment.replace(PLACEHOLDER_TOKEN, (token) => `\`${token}\``)
    )
    .join('')
    .replaceAll('|', '\\|');
}

/** A bare identifier of a literal kind is shown as code; a described spelling is shown as prose. */
function retiredCell(entry: RetirementEntry): string {
  return LITERAL_KINDS.has(entry.kind) && BARE_SPELLING.test(entry.retired)
    ? `\`${entry.retired}\``
    : cell(entry.retired);
}

function replacementCell(entry: RetirementEntry): string {
  return cell(entry.replacement);
}

/** A table padded the way Prettier pads it, so the format gate agrees with the bytes. */
function renderTable(header: readonly string[], rows: readonly (readonly string[])[]): string {
  const widths = header.map((title, column) =>
    Math.max(title.length, 3, ...rows.map((row) => (row[column] ?? '').length))
  );
  const line = (cells: readonly string[]): string =>
    `| ${cells.map((text, column) => text.padEnd(widths[column] ?? 0)).join(' | ')} |`;
  return [
    line(header),
    `| ${widths.map((width) => '-'.repeat(width)).join(' | ')} |`,
    ...rows.map(line),
  ].join('\n');
}

/** The page for a set of entries; pure. */
export function renderUpgradingPage(entries: readonly RetirementEntry[]): string {
  const rows = [...entries]
    .sort(compareForPage)
    .map((entry) => [
      retiredCell(entry),
      replacementCell(entry),
      entry.refusedIn,
      entry.forgetAfter,
    ]);
  return [
    HEADER_COMMENT,
    '',
    '# Upgrading',
    '',
    OPENING,
    '',
    renderTable(HEADER, rows),
    '',
    CLOSING,
    '',
  ].join('\n');
}

function main(): void {
  const entries = listRetirements();
  writeFileSync(path.join(REPO_ROOT, UPGRADING_PAGE), renderUpgradingPage(entries), 'utf8');
  writeFileSync(
    path.join(REPO_ROOT, 'server', RETIREMENT_PROJECTION),
    renderRetirementProjection(entries),
    'utf8'
  );
  console.log(
    `✓ Wrote ${UPGRADING_PAGE} and server/${RETIREMENT_PROJECTION} (${entries.length} entries)`
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    main();
  } catch (error) {
    console.error(error);
    process.exitCode = 1;
  }
}
