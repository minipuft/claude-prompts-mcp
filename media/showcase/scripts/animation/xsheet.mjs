#!/usr/bin/env node
// Writes the exposure sheet: one row per frame of the timeline (v3/timeline.json), the projection of pacing, blocking, camera, keys,
// light and look onto frames. No rendering: it reads src/scenes/animaticPlan.ts, the module the Animatic composition draws from.
// usage: node scripts/animation/xsheet.mjs [--out <path>] [--json-out <path>]
// Writes two files: v3/xsheet.html (to read) and v3/xsheet.json (to probe: scripts/animation/README.md "What the probes read").
import fs from 'node:fs';
import path from 'node:path';
import {loadTs, root} from './load-ts.mjs';

const i = process.argv.indexOf('--out');
const outPath = path.resolve(i > -1 ? process.argv[i + 1] : path.join(root, 'v3/xsheet.html'));
const j = process.argv.indexOf('--json-out');
const jsonPath = path.resolve(j > -1 ? process.argv[j + 1] : path.join(root, 'v3/xsheet.json'));

const {timeline, xstateOf} = await loadTs('src/scenes/animaticPlan.ts');
const {XHEADER, xsheetRow, xsheetJsonRows} = await loadTs('src/library/animation/xsheet.ts');

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const states = Array.from({length: timeline.durationInFrames}, (_, f) => xstateOf(f));
const rows = states.map(xsheetRow);

const beatStart = new Set(timeline.beats.map((b) => b.start));
const body = rows
  .map((r) => {
    const cls = [beatStart.has(Number(r[0])) ? 'beat' : '', r[11] ? 'crossing' : '', r[4].startsWith('breakdown') ? 'breakdown' : ''].filter(Boolean).join(' ');
    return `<tr class="${cls}">${r.map((c, k) => (k === 10 && c ? `<td><i style="background:${esc(c)}"></i>${esc(c)}</td>` : `<td>${esc(c)}</td>`)).join('')}</tr>`;
  })
  .join('\n');

const html = `<!doctype html>
<meta charset="utf-8">
<title>Exposure sheet · ${timeline.durationInFrames} frames</title>
<style>
  body { background: #07060c; color: #d9e5e3; font: 12px/1.35 ui-monospace, 'IBM Plex Mono', monospace; margin: 24px; }
  h1 { font: 600 18px system-ui, sans-serif; } p { color: #56b0d4; max-width: 90ch; }
  table { border-collapse: collapse; } th { text-align: left; color: #56b0d4; position: sticky; top: 0; background: #07060c; border-bottom: 1px solid #56b0d4; padding: 2px 10px; }
  td { padding: 0 10px; white-space: nowrap; } tr:nth-child(even) td { background: #0b0a12; }
  tr.beat td { border-top: 2px solid #56b0d4; color: #fff; } tr.crossing td { color: #f2c56a; } tr.breakdown td:nth-child(5), tr.breakdown td:nth-child(6) { color: #9fe8ff; }
  i { display: inline-block; width: 10px; height: 10px; margin-right: 6px; border: 1px solid #56b0d4; }
</style>
<h1>Exposure sheet · ${rows.length} frames at ${timeline.fps} fps</h1>
<p>One row per frame. <b>drawing (held)</b> is the key the animatic holds; <b>chart</b> is what the animatic draws (a key on the frame it comes on, then its hold; each key stays exactly the hold it declares and the next is drawn from there, no breakdowns). Rows in amber are inside a crossing; a ruled row starts a beat. Placeholder keys (liftChart) are used where a shot's key sheet is not drawn yet. Generated by scripts/animation/xsheet.mjs; do not edit.</p>
<table>
<thead><tr>${XHEADER.map((h) => `<th>${esc(h)}</th>`).join('')}</tr></thead>
<tbody>
${body}
</tbody>
</table>
`;
fs.writeFileSync(outPath, html);
const jsonRows = xsheetJsonRows(states);
fs.writeFileSync(jsonPath, JSON.stringify({rows: jsonRows}) + '\n');
const written = (html.match(/<tr class=/g) ?? []).length;
console.log(`xsheet: ${rows.length} rows (${written} <tr> in the file) for ${timeline.durationInFrames} frames -> ${path.relative(root, outPath)}; ${jsonRows.length} rows -> ${path.relative(root, jsonPath)}`);
process.exit(written === timeline.durationInFrames && jsonRows.length === timeline.durationInFrames ? 0 : 1);
